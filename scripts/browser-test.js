const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const {server}=require('./test-server')(process.argv[2]);
(async()=>{
 await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const browser=await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader','--use-angle=swiftshader']});
 try{
  for(const viewport of [{width:1280,height:800},{width:390,height:844}]){
   const page=await browser.newPage({viewport,colorScheme:'dark'}),errors=[];
   page.on('pageerror',e=>errors.push(e.message));
   await page.goto('http://127.0.0.1:'+server.address().port+'/');
   assert.equal(await page.locator('#settings button').count(),0,'settings contains only configuration');
   assert.equal(await page.locator('#overview').count(),0);
   for(const id of ['grow','shuffle','export','fit'])assert.equal(await page.locator('#map-tools #'+id).count(),1);
   const pick=async(id,name)=>{await page.locator('#'+id).fill(name);await page.locator('#'+id+'-options button').first().click({timeout:20000})};
   await pick('from','Tom Morello');
   assert.equal(await page.locator('#network').isVisible(),false,'choosing a suggestion does not launch a second search');
   await page.locator('#submit').click();
   await page.locator('#result h2').getByText('Tom Morello',{exact:true}).waitFor({timeout:20000});
   await page.locator('#detail strong').getByText('Tom Morello',{exact:true}).waitFor();
   assert.equal(await page.locator('#dimension button[aria-pressed=true]').textContent(),'2D');
   assert.ok(await page.locator('#network canvas').first().isVisible());
   assert.equal(await page.locator('#records').textContent(),'','no implicit timeline request');
   await page.locator('#detail').getByRole('button',{name:'Evidence',exact:true}).click();
   await page.locator('#records .evidence-record').first().waitFor({timeout:20000});
   await page.locator('#detail').getByRole('button',{name:'Memberships',exact:true}).click();
   await page.locator('#records h2').getByText('Memberships & roles').waitFor();
   await page.locator('#dimension [data-dimension="3D"]').click();
   await page.locator('#dimension [data-dimension="3D"][aria-pressed=true]').waitFor();
   await page.locator('#dimension [data-dimension="2D"]').click();
   assert.equal(await page.locator('#dimension button[aria-pressed=true]').textContent(),'2D');
   await page.locator('#settings summary').click();
   const edges=()=>page.evaluate(()=>[...model.links.keys()].sort());
   const original=await edges();
   const positions=()=>page.evaluate(()=>viewer.cy.nodes().map(n=>[n.id(),{...n.position()}]));
   const beforeAppearance=await positions();
   await page.locator('#node-size').fill('1.4');
   assert.equal(await page.locator('output[for="node-size"]').textContent(),'1.4');
   assert.deepEqual(await edges(),original);
   assert.deepEqual(await positions(),beforeAppearance,'appearance slider must not move the map');
   await page.locator('#node-size').fill('1');
   await page.locator('#fraction').fill('0');
   await page.locator('#status').getByText('Map updated · 0 links',{exact:true}).waitFor({timeout:20000});
   assert.deepEqual(await edges(),[]);
   await page.locator('#fraction').fill('0.4');
   await page.locator('#status').getByText('Map updated · '+original.length+' links',{exact:true}).waitFor({timeout:20000});
   assert.deepEqual(await edges(),original,'restoring a slider restores the same graph');
   await page.locator('#depth').fill('1');
   await page.locator('#max-connections').fill('25');
   await page.locator('#max-branch').fill('3');
   await page.locator('#max-branch').press('Tab');
   await page.locator('#status').getByText(/Map updated/).waitFor({timeout:20000});
   await page.locator('#settings summary').click();
   await page.locator('#detail strong').getByText('Tom Morello',{exact:true}).waitFor({timeout:20000});
   const count=async()=>Number((await page.locator('#map-count').textContent()).match(/(\d+) links/)[1]);
   const before=await count();assert.ok(before<=3);
   await page.locator('#detail').getByRole('button',{name:'Expand',exact:true}).click();
   await page.locator('#submit:enabled').waitFor({timeout:20000});
   assert.ok(await count()>before,'ranked expansion adds new edges');
   const old=await edges();
   for(let i=0;i<3;i++){await page.locator('#grow').click();await page.locator('#submit:enabled').waitFor({timeout:30000});}
   const grown=await edges();
   assert.ok(grown.length>old.length);
   assert.ok(old.every(id=>grown.includes(id)),'growth retains existing links');
   if(await page.evaluate(()=>model.nodes.size)>200)await page.waitForFunction(()=>!viewer.layoutWorker,{timeout:30000});
   await page.locator('#filters summary').click();
   for(const input of await page.locator('#filter-options input').all())await input.uncheck();
   assert.equal(await page.locator('#network').isVisible(),false,'filter change invalidates old graph');
   await page.locator('#submit').click();
   await page.locator('#map-count').getByText('1 artists · 0 links',{exact:true}).waitFor({timeout:20000});
   await page.locator('#reset').click();
   assert.equal(await page.locator('#from').inputValue(),'');
   assert.equal(await page.locator('#network').isVisible(),false);
   assert.equal(await page.locator('#filter-count').textContent(),'(5/5)');
   await page.locator('[data-mode=path]').click();
   await pick('from','Tom Morello');await pick('to','David Bowie');await page.locator('#submit').click();
   await page.locator('#result h2').getByText('Connection path',{exact:true}).waitFor({timeout:20000});
   const chain=page.getByLabel('Connection chain');if(await chain.count())await chain.selectOption('1');
   await page.locator('#result').getByRole('button',{name:'Tom Morello',exact:true}).click();
   await page.locator('#detail').getByRole('button',{name:'Next',exact:true}).click();
   await page.locator('#detail').getByRole('button',{name:'Previous',exact:true}).click();
   assert.ok(await page.locator('#network canvas').first().isVisible());
   assert.ok(await page.locator('#result a[href^="https://open.spotify.com/search/"]').count());
   assert.deepEqual(errors,[]);
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
   console.log('Browser passed',viewport.width,'px');
   await page.close()
  }
 }finally{await browser.close();server.close()}
})().catch(e=>{console.error(e);server.close();process.exitCode=1});
